"""Corpus statistics -> stats/stats.json and stats/STATS.md.

Counts docs / sentences / words / chars per source, per genre, per split and overall;
religious vs non-religious split; top-N vocabulary; character inventory; parallel counts.
"""
from __future__ import annotations

import json
import re
import unicodedata
from collections import Counter, defaultdict

from . import config
from .jsonl import read_jsonl

SENT_END = re.compile(r"(?<=[.!?])[\"')\]]*\s+|\n+")
WORD = re.compile(r"[^\W\d_]+(?:'[^\W\d_]+)*", re.UNICODE)


def count_sentences(text: str) -> int:
    return sum(1 for s in SENT_END.split(text) if s and s.strip())


def _blank():
    return {"docs": 0, "sentences": 0, "words": 0, "chars": 0}


def _add(acc: dict, text: str) -> None:
    acc["docs"] += 1
    acc["sentences"] += count_sentences(text)
    acc["words"] += len(text.split())
    acc["chars"] += len(text)


def compute(top_n: int = 100) -> dict:
    per_source, per_genre, per_split = defaultdict(_blank), defaultdict(_blank), defaultdict(_blank)
    rel = {"religious": _blank(), "non-religious": _blank()}
    licenses = defaultdict(Counter)
    overall = _blank()
    vocab: Counter = Counter()
    chars: Counter = Counter()
    for split in ("train", "dev", "test"):
        p = config.MONO / f"{split}.jsonl"
        if not p.exists():
            continue
        for d in read_jsonl(p):
            t = d["text"]
            for acc in (per_source[d["source"]], per_genre[d["genre"]], per_split[split], overall,
                        rel["religious" if d["genre"] == "religious" else "non-religious"]):
                _add(acc, t)
            licenses[d["source"]][d["license"]] += 1
            if split == "train":
                vocab.update(w.lower() for w in WORD.findall(t))
                chars.update(t)
    parallel = {}
    for p in sorted(config.PARALLEL.glob("*.jsonl*")):  # plain or gzip shards
        for r in read_jsonl(p):
            parallel.setdefault(r["source"], Counter())[r["translation_lang"]] += 1
    parallel = {k: dict(v) for k, v in parallel.items()}
    unverified = {}
    for p in sorted(config.UNVERIFIED.glob("*.jsonl")):
        c = Counter(r["source"] for r in read_jsonl(p))
        unverified[p.stem] = dict(c)
    char_inv = [
        {"char": c, "codepoint": f"U+{ord(c):04X}", "name": unicodedata.name(c, "?"), "count": n}
        for c, n in sorted(chars.items(), key=lambda x: -x[1]) if c not in "\n"
    ]
    rel_total = rel["religious"]["words"] + rel["non-religious"]["words"]
    return {
        "overall": overall,
        "per_split": dict(per_split),
        "per_source": dict(sorted(per_source.items(), key=lambda x: -x[1]["words"])),
        "per_genre": dict(sorted(per_genre.items(), key=lambda x: -x[1]["words"])),
        "religious_split": {**rel, "religious_word_share": round(rel["religious"]["words"] / max(1, rel_total), 4)},
        "licenses_per_source": {k: dict(v) for k, v in licenses.items()},
        "parallel_pairs": parallel,
        "unverified": unverified,
        "vocab_size_train": len(vocab),
        "top_vocab": vocab.most_common(top_n),
        "char_inventory": char_inv,
    }


def _table(title: str, rows: dict) -> list[str]:
    out = [f"### {title}", "", "| name | docs | sentences | words | chars |", "|---|---:|---:|---:|---:|"]
    for k, v in rows.items():
        out.append(f"| {k} | {v['docs']:,} | {v['sentences']:,} | {v['words']:,} | {v['chars']:,} |")
    return out + [""]


def to_markdown(s: dict) -> str:
    L = ["# Kikamba corpus statistics", "", "Generated by `corpus stats` (main bucket only; unverified excluded).", ""]
    L += _table("Overall", {"all": s["overall"]})
    L += _table("Per split", s["per_split"])
    rs = s["religious_split"]
    L += _table("Religious vs non-religious", {"religious": rs["religious"], "non-religious": rs["non-religious"]})
    L += [f"Religious share of words: **{rs['religious_word_share'] * 100:.1f}%**", ""]
    L += _table("Per source", s["per_source"])
    L += _table("Per genre", s["per_genre"])
    L += ["### Parallel pairs (data/parallel)", "", "| source | target lang | pairs |", "|---|---|---:|"]
    for src, c in s["parallel_pairs"].items():
        for lang, n in c.items():
            L.append(f"| {src} | {lang} | {n:,} |")
    L += ["", "### Unverified bucket (data/unverified, NOT in train.txt)", "", "| file | source | records |",
          "|---|---|---:|"]
    for f, c in s["unverified"].items():
        for src, n in c.items():
            L.append(f"| {f} | {src} | {n:,} |")
    L += ["", f"### Top {len(s['top_vocab'])} words (train, lowercased; {s['vocab_size_train']:,} types)", ""]
    L.append(", ".join(f"{w} ({n:,})" for w, n in s["top_vocab"]))
    L += ["", "### Character inventory (train)", "", "| char | code point | name | count |", "|---|---|---|---:|"]
    for c in s["char_inventory"]:
        shown = c["char"] if c["char"].isprintable() and not c["char"].isspace() else repr(c["char"])
        shown = shown.replace("|", "\\|")
        L.append(f"| {shown} | {c['codepoint']} | {c['name']} | {c['count']:,} |")
    return "\n".join(L) + "\n"


def run() -> dict:
    config.ensure_dirs()
    s = compute()
    (config.STATS_DIR / "stats.json").write_text(json.dumps(s, indent=1, ensure_ascii=False), encoding="utf-8")
    (config.STATS_DIR / "STATS.md").write_text(to_markdown(s), encoding="utf-8")
    return s
